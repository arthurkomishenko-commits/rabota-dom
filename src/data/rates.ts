/**
 * Репозиторий ставок калькулятора.
 *
 * Что делает: отдаёт ставки и состояние их калибровки. Единственное место,
 * знающее, откуда они берутся (ARCHITECTURE_PRINCIPLES §2).
 * Кто использует: страница калькулятора (F7).
 *
 * Импорт статический, а не запрос по сети — требование брифа §6: ставки
 * попадают в бандл и не зависят от доступности сети в момент расчёта.
 *
 * ДЕНЬГИ — ЦЕЛЫЕ АГОРОТЫ (§3 принципов). Ни одного расчёта в шекелях
 * с плавающей точкой: округление копеек в цене — это классический источник
 * расхождений, которые потом невозможно объяснить клиенту.
 */
import rates from './rates.json';

export type RatesStatus = 'draft' | 'production';

export const RATES = rates;

/**
 * Пока ставки не подтверждены, калькулятор работает в режиме «в калибровке»
 * и скрыт из меню. Это не флаг «выключить фичу», а честное состояние:
 * показывать неподтверждённую цифру как цену нельзя.
 */
export const ratesStatus = (): RatesStatus => rates.status as RatesStatus;

export const ratesAreCalibrated = (): boolean => ratesStatus() === 'production';
